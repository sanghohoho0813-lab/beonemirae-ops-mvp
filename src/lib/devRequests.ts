// ─────────────────────────────────────────────────────────────────────────────
// 개발자에게 요청하기 — 역할별 점검 항목
//
//  ── 왜 「주제 5개 × 선택지 4~5개」 인가 ─────────────────────────────────
//
//  처음에는 역할마다 항목 다섯 개를 평면으로 늘어놓았습니다. 그러면 하나를
//  고를 때마다 "내 얘기가 이 다섯 중에 없는데" 가 됩니다. 실제로 불편한 것은
//  「수거 입력」 안의 어느 대목이지, "수거 입력이 불편하다" 가 아닙니다.
//
//  그래서 주제를 여섯 일곱 개로 나누고, 주제마다 실제로 일어나는 일 네댓
//  가지를 적었습니다. 고르는 사람은 자기 주제를 먼저 찾고 그 안에서 고릅니다.
//
//  ⚠ 0076 — 목록을 **지금 화면 기준으로 다시 썼습니다.** 예전 목록은
//    「잘못 넣은 것을 고치기가 어렵습니다」처럼 이미 해결한 것을 묻고 있었고,
//    반대로 그 뒤에 생긴 것(자재 규격 · 공용차 · 오늘 업무 마감 · 기록 정정)은
//    고를 자리가 아예 없었습니다. 이미 끝난 일을 계속 물으면 답이 쌓여도
//    쓸 데가 없습니다.
//  ⚠ **앞으로도 계속 다듬어 갈 것**만 남깁니다 — 한 번 정하고 끝나는 것
//    (예: 색·글꼴)은 여기서 묻지 않습니다.
//  ⚠ 여러 개 고를 수 있고, 마지막에는 늘 직접 적는 칸이 있습니다.
//  받는 쪽도 「수거 입력 › 저장이 안 되거나 중간에 끊깁니다」 처럼 어디의
//  무엇인지 바로 읽힙니다.
//
//  ── 항목을 고른 기준 ────────────────────────────────────────────────────
//
//  한 번 고치면 끝나는 것이 아니라 **앞으로도 계속 확인해야 하는 것**으로만
//  채웠습니다. 사람이 바뀌고 거래처가 늘면 다시 어긋나는 것들입니다.
//  "버튼 색을 바꿔 주세요" 같은 한 번짜리는 자유 의견에 적으면 됩니다.
//
//  고른 문구는 「주제 › 선택지」 형태로 DB 에 **그대로** 저장합니다(0022).
//  여기 문구를 나중에 고쳐도 예전 요청이 무슨 뜻이었는지 남아야 합니다.
// ─────────────────────────────────────────────────────────────────────────────

