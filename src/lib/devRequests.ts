/** 「주제 › 선택지」 — DB 에 저장하고 요청함에 보여 주는 형태 */
export const devTopicLabel = (subject: string, option: string) => `${subject} › ${option}`

/** 이 역할이 개발 요청을 보낼 수 있는지 (내부 직원만) */
export function canSendDevRequest(role: UserRole | null): boolean {
  return role === 'admin' || role === 'office' || role === 'field'
}

