// 점검용 계정 가려내기
//
//  파일럿 전에 권한·격리를 확인하려고 만든 계정들이 있습니다
//  (「[검증]…」, 「김상호(테스트용)」). 계정 자체는 남겨 둡니다 — 지우면
//  그 계정으로 남긴 기록의 주인이 사라집니다.
//
//  다만 **실제 업무에서 고르는 목록**에는 나오면 안 됩니다. 담당 기사 배정은
//  한 명이라도 붙는 순간 「그 사람에게만 보이는」 상태로 바뀌기 때문에,
//  점검용 계정이 잘못 눌리면 그 거래처가 진짜 기사 화면에서 사라집니다.
//
//  ⚠ 이름으로 가려냅니다. DB 에 「점검용」 표시 칸이 없어서인데, 칸을 새로
//    만들면 마이그레이션이 필요하고 기존 계정을 전부 손봐야 합니다. 지금은
//    이름 규칙이 분명해서(대괄호 검증 / 괄호 테스트용) 이것으로 충분합니다.
//    나중에 표시 칸이 생기면 이 함수만 바꾸면 됩니다.
// ─────────────────────────────────────────────────────────────────────────────

/** 「[검증]」 「검증용」 「테스트」 「test」 가 이름이나 메일에 들어간 계정 */
export function isTestAccount(name?: string | null, email?: string | null): boolean {
  const hay = `${name ?? ''} ${email ?? ''}`
  return /\[검증\]|검증용|검증\s*계정|테스트|test/i.test(hay)
}
