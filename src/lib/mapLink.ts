//    주소가 틀렸으면 지도도 틀린 곳을 보여 주고, 그게 고칠 신호입니다.
// ─────────────────────────────────────────────────────────────────────────────

export function mapUrl(address: string | null | undefined): string | null {
  const a = (address ?? '').trim()
  if (!a) return null
  return `https://map.kakao.com/link/search/${encodeURIComponent(a)}`
}
