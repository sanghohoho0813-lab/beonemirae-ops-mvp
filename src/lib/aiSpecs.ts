/** 한 자리가 실제로 도는 방식 — 한 단계 */
export interface AiStep {
  /** 무엇을 하는 단계인지 */
  title: string
  /** 그 단계가 실제로 무엇을 다루는지 */
  detail: string
}

export type AiStage = '1단계' | '2단계' | '3단계'

export interface AiSpec {
  id: AiSpecId
  /** 넓은 화면 단추에 적는 이름 */
  label: string
  /** 폰에서 쓰는 짧은 이름 */
  shortLabel: string
  /** 창 제목 */
  title: string
  stage: AiStage
  /** 어느 화면에 있는 자리인지 — 목록에서 씁니다 */
  where: string
  /** 「아직 켜지지 않았습니다」 바로 아래 문단 — 무엇을 아직 안 했는지 */
  notYet: string
  /** 무엇을 위한 것인가 — 지금 실제로 불편한 일 */
  why: string
  /** 켜지면 어떻게 도는가 */
  how: AiStep[]
  /** 무엇을 재료로 쓰는가 — 실제로 저희 서버에 있는 자료만 적습니다 */
  uses: string[]
  /** AI 가 정하지 않는 것 — 사람이 정합니다 */
  never: string[]
  /** 붙이기 전에 먼저 있어야 하는 것 */
  needs: string
  /** 어느 서비스를 부를 예정인가 — 안 정했으면 안 정했다고 적습니다 */
  api: string
  /**
   *  예정 기능 목록 — **있는 자리에만** 둡니다.
   *  ⚠ 늘어놓을수록 「이미 되는 것」처럼 보입니다. 넷을 넘기지 않습니다.
   */
  planned?: { label: string; desc: string }[]
}

