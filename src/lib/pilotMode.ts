/** Pilot 동안 내려 둘 것들 */
export interface PilotHidden {
  /**
   * 병원 수거요청 — 메뉴 · 경고 · 배지 · 분석 카드 전부.
   *
   *  ⚠ 이력은 지우지 않습니다. 다시 켜면 과거 요청도 그대로 보입니다.
   */
  clientRequests: boolean
  /**
   * 소모품 주문·판매 — 다음 단계 기능입니다.
   *
   *  대표님: 「"이것도 지금 써야 하나?" 라고 생각하지 않도록 하는 게 중요하다.」
   */
  supplies: boolean
}

/**
 * 지금 무엇을 내려 두는가.
 *
 *  ⚠ 다시 켜는 법 — 여기 값을 `false` 로 바꾸고 배포하면 끝입니다.
 *    화면 어디에도 따로 고칠 곳이 없습니다.
 *
 *  ⚠ `.env` 로 빼지 않은 이유 — 대표님이 직접 켜고 끄실 값이 아니라
 *    「Pilot 이 끝나면 개발자가 되돌릴 값」입니다. 환경변수로 두면 배포
 *    환경마다 화면이 달라져서, 대표님 화면과 이사님 화면이 서로 다른
 *    상태가 될 수 있습니다.
 */
export const PILOT_HIDDEN: PilotHidden = {
  clientRequests: true,
  supplies: true,
}

/** 병원 요청을 화면에서 내려 두는가 */
export const hideRequests = (): boolean => PILOT_HIDDEN.clientRequests

/** 소모품 주문을 화면에서 내려 두는가 */
export const hideSupplies = (): boolean => PILOT_HIDDEN.supplies

/**
 * Pilot 동안 안 쓰는 화면인가 — 주소로 판단합니다.
 *
 *  ⚠ 메뉴에서만 빼면 주소를 직접 치거나 옛 링크를 누를 때 그대로 열립니다.
 *    그러면 「메뉴엔 없는데 왜 열리지」가 됩니다. 라우트에서도 같이 봅니다.
 */
export function isHiddenRoute(path: string): boolean {
  if (hideRequests() && path.startsWith('/requests')) return true
  if (hideSupplies() && path.startsWith('/supplies')) return true
  return false
}
