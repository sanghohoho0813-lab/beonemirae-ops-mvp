// ─────────────────────────────────────────────────────────────────────────────
// Pilot 모드 — 지금 실제로 쓰는 것만 보이게 (0080)
//
//  대표님: 「송현주 이사님 / 송현근 대표님이 처음 시스템을 쓸 때 불필요한
//  기능·알림·경고 때문에 헷갈리지 않도록, 지금 당장 실제로 쓸 핵심 업무만
//  보이게 만드는 것이 목표다. 현재 기능은 가능하면 삭제하지 말고, Pilot 동안
//  숨기거나 비활성화하는 방향을 우선해줘.」
//
//  ── 여기서 지키는 것 ──────────────────────────────────────────────────────
//
//  ⚠ **아무것도 지우지 않습니다.** 화면에서 내리기만 합니다. 코드도, 표도,
//    지금까지 쌓인 요청 이력도 그대로 있습니다. 아래 스위치 하나를 끄면
//    전부 예전처럼 돌아옵니다 — 그때 과거 데이터도 그대로 보입니다.
//
//  ⚠ 스위치는 **한 곳**입니다. 화면마다 `if (역할 === …)` 를 흩어 놓으면
//    다시 켤 때 한 군데는 반드시 빠집니다.
//
//  ⚠ 서버는 건드리지 않습니다. RLS·권한·감사기록·정산·재고는 그대로입니다.
//    숨기는 것은 **보이는 것**뿐이고, 막는 것은 서버가 하던 대로 합니다.
// ─────────────────────────────────────────────────────────────────────────────

/** Pilot 동안 내려 둘 것들 */
export interface PilotHidden {
  /**
   * 병원 수거요청 — 메뉴 · 경고 · 배지 · 분석 카드 전부.
   *
   *  ⚠ 이력은 지우지 않습니다. 다시 켜면 과거 요청도 그대로 보입니다.
   */
  clientRequests: boolean
  /**
   * 소모품 주문·판매.
   *
   *  ⚠ 지금은 **켜 둡니다** (0081). 대표님: 「소모품주문 화면은 다시 띄워줘.
   *    실사 당시에 보여줘야 되거든.」 실사에서 보여 드릴 화면이라
   *    Pilot 동안에도 열어 둡니다.
   */
  supplies: boolean
}

/**
 * 지금 무엇을 내려 두는가.
 *
 *  ⚠ 다시 켜는 법 — 여기 값을 `false` 로 바꾸고 배포하면 끝입니다.
 *    화면 어디에도 따로 고칠 곳이 없습니다.
 *
 *  ⚠ `.env` 로 빼지 않은 이유 — 대표님이 직접 켜고 끄실 값이 아니라
 *    「Pilot 이 끝나면 개발자가 되돌릴 값」입니다. 환경변수로 두면 배포
 *    환경마다 화면이 달라져서, 대표님 화면과 이사님 화면이 서로 다른
 *    상태가 될 수 있습니다.
 */
export const PILOT_HIDDEN: PilotHidden = {
  //  0083 — **다시 켰습니다.**
  //
  //   0080 에서 Pilot 동안 내려 뒀는데, 이번 고객 포털 고도화의 핵심이
  //   「병원이 포털에서 올린 요청을 내부에서 한 화면으로 처리한다」입니다.
  //   요청함이 닫혀 있으면 병원이 올린 요청을 아무도 못 봅니다 — 포털을
  //   드리는 순간 그건 **고장**입니다.
  //
  //   ⚠ 0080 에서 함께 고친 집계 결함(내려 둔 요청·처리 완료 요청이 첫
  //     화면 경고에 계속 세지던 것)은 **그대로 남습니다.** 그건 숨긴 것이
  //     아니라 계산을 고친 것이라 스위치와 무관합니다.
  clientRequests: false,
  //  0081 — 실사에서 보여 드릴 화면이라 다시 켰습니다.
  supplies: false,
}

/** 병원 요청을 화면에서 내려 두는가 */
export const hideRequests = (): boolean => PILOT_HIDDEN.clientRequests

/** 소모품 주문을 화면에서 내려 두는가 */
export const hideSupplies = (): boolean => PILOT_HIDDEN.supplies

/**
 * Pilot 동안 안 쓰는 화면인가 — 주소로 판단합니다.
 *
 *  ⚠ 메뉴에서만 빼면 주소를 직접 치거나 옛 링크를 누를 때 그대로 열립니다.
 *    그러면 「메뉴엔 없는데 왜 열리지」가 됩니다. 라우트에서도 같이 봅니다.
 */
export function isHiddenRoute(path: string): boolean {
  if (hideRequests() && path.startsWith('/requests')) return true
  if (hideSupplies() && path.startsWith('/supplies')) return true
  return false
}
