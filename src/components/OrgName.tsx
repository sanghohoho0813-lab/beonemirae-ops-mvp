// 병원 이름 줄바꿈 (0148)
//
//  「의료법인한양의료재단」처럼 띄어쓰기 없는 법인 이름은 폭이 모자라면 아무 데서나
//  끊겼습니다(「의료법인한양의 / 료재단」). 이름을 바꾸지 않고, 법인 말머리 뒤에만
//  끊을 자리(<wbr>)를 둡니다 → 「의료법인 / 한양의료재단」.
//  ⚠ 글자는 그대로입니다 — 복사 · 검색 · 화면 읽기 프로그램에는 원래 이름 그대로.
// ─────────────────────────────────────────────────────────────────────────────

const PREFIX = /^(의료법인|재단법인|사회복지법인|사단법인|학교법인)(?=\S)/

export function OrgName({ name }: { name: string }) {
  const m = name.match(PREFIX)
  if (!m) return <>{name}</>
  return (
    <>
      {m[1]}
      <wbr />
      {name.slice(m[1].length)}
    </>
  )
}
