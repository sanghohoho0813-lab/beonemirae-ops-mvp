export interface Facility {
  id: string
  name: string
  wasteType: WasteType
  region: string
  /** 인계 가능 시간 */
  handoverWindow: string
  /** 오늘 인계 예정 차량 id */
  vehicleIds: string[]
  /** 처리장 도착 목표 시간 */
  targetTime: string
}

