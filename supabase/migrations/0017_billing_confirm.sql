-- ─────────────────────────────────────────────────────────────────────────────
-- 0017. 청구 확정 — 정산 결과를 '받을 돈' 으로 굳힙니다
--
--  지금까지 이 시스템에서 끊기는 곳은 한 군데였습니다.
--
--    수거 입력 → 자재·재고 → 월 정산 → 거래명세서   여기까지 자동
--    월 정산 → 청구(미수금)                          여기가 끊김
--
--  정산 금액이 나와도 그것을 받을 돈으로 옮기는 길이 화면에 없어서, 미수금
--  화면은 비어 있고 대시보드 미수금 합계도 0원으로 나왔습니다. 그래서
--  이사님은 「정산금 세부내역」의 AE열(정산완료/미수금)을 엑셀에 그대로
--  두고 계셔야 했습니다.
--
--  이 마이그레이션은 사무실이 월 정산을 확인한 뒤 「청구 확정」을 누르면
--  그 달의 금액이 그대로 굳도록 payments 에 두 칸을 더합니다.
--
--   1) status 에 '취소' 를 더합니다
--      잘못 만든 청구를 지우지 않고 취소로 남깁니다. 지워 버리면 "그런
--      청구는 없었다" 가 되어, 병원과 금액을 두고 다툴 때 근거가 없습니다.
--
--   2) snapshot (jsonb) 을 더합니다
--      확정한 순간의 정산·명세서 내용을 통째로 담습니다. 여기에는 그 청구가
--      덮은 수거·공급의 id 도 함께 들어갑니다. 이 한 칸이 세 가지를 만듭니다.
--
--        · 나중에 단가를 바꿔도 이미 확정한 청구와 명세서는 흔들리지 않습니다
--          (지금은 단가를 바꾸면 지난달 명세서 금액까지 같이 바뀝니다 —
--           실측: 7월 100kg 수거가 95,000원 → 단가 변경 후 150,000원)
--        · 청구 뒤에 들어온 추가 수거는 기존 청구에 섞이지 않고, 다음
--          「추가 청구」로 따로 잡힙니다
--        · 같은 달에 청구할 것이 남지 않았으면 버튼이 잠깁니다 (중복 차단)
--
--   3) canceled_at 을 더합니다 — 언제 취소했는지. 누가 취소했는지는
--      감사기록(payment.cancel)에 남습니다.
--
--  이 파일은 데이터를 지우거나 바꾸지 않습니다. 칸을 더하고 status 에 값
--  하나를 허용할 뿐이며, 기존 청구는 그대로 있습니다.
--
--  적용 후에는 supabase/test/40_billing_confirm.mjs 로 확인할 수 있습니다.
-- ─────────────────────────────────────────────────────────────────────────────

-- 1) '취소' 상태 허용 ---------------------------------------------------------
alter table public.payments drop constraint if exists payments_status_check;
alter table public.payments
  add constraint payments_status_check
  check (status in ('입금완료', '미수금', '확인필요', '취소'));

-- 2) 확정 당시의 정산·명세서 내용 ---------------------------------------------
alter table public.payments add column if not exists snapshot jsonb;
comment on column public.payments.snapshot is
  '청구 확정 시점의 정산·거래명세서 내용과 덮은 수거·공급 id. 이후 단가 변경이나 추가 수거가 이 청구를 바꾸지 못하게 합니다.';

-- 3) 취소 시각 ---------------------------------------------------------------
alter table public.payments add column if not exists canceled_at timestamptz;
comment on column public.payments.canceled_at is
  '청구를 취소한 시각. 누가 취소했는지는 audit_logs(payment.cancel)에 남습니다.';
