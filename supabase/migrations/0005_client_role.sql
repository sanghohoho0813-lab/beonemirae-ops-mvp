-- 병원 고객 역할 추가 (5단계 — 병원 운영지원 서비스 확장)
--
--  지금까지 계정은 비원미래 내부 직원(admin/office/field)뿐이었습니다.
--  병원 담당자가 자기 병원의 운영현황을 직접 확인하고 요청을 올릴 수 있도록
--  'client' 역할을 추가합니다.
--
--  ※ 파일을 분리한 이유
--     Postgres 는 ALTER TYPE ... ADD VALUE 로 추가한 enum 값을 같은 트랜잭션
--     안에서 사용할 수 없습니다. 그래서 값 추가(0005)와 이 값을 쓰는 정책·제약
--     (0006)을 서로 다른 마이그레이션 파일로 나눕니다.
-- ─────────────────────────────────────────────────────────────────────────────

alter type public.user_role add value if not exists 'client';
