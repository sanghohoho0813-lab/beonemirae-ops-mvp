-- ─────────────────────────────────────────────────────────────────────────────
-- 0035. 월정액 계약 — 수거가 0건인 달의 청구 정책
--
--  무엇이 문제였나
--
--   월정액 거래처(오남한양 월 900만 · 해올 의료 130만 + 지정 300만)는
--   지금 **그 달에 완료 수거가 1건이라도 있을 때만** 월정액을 청구합니다.
--   계약 전·해지 후 달에 기본요금이 저절로 나가는 사고를 막는 규칙이고,
--   실제 엑셀 11개와도 맞습니다 — 요금이 적힌 달은 전부 수거가 있던
--   달이었습니다.
--
--   그런데 월정액 계약 중에는 **수거가 없어도 계약상 청구하는** 것이
--   있습니다. 병원이 그 달에 배출을 안 했다고 기본료가 면제되지는 않는
--   계약입니다. 지금은 그런 달이 월말 청구 목록에서 「수거 기록이
--   없습니다 — 계약서상 청구 대상인지 확인해 주세요」로 빠지고, 이사님이
--   거래처 화면에서 손으로 만들어야 합니다. 매달 반복됩니다.
--
--  무엇을 저장하는가
--
--   flat_fee_when_empty — 이 거래처의 월정액을 수거 0건인 달에도
--   청구하는지. **계약서를 보고 사람이 정하는 값**입니다.
--
--     null / false  지금까지와 같음. 수거가 있을 때만 청구하고,
--                   0건인 달은 「확인 필요」로 사람에게 돌립니다.
--     true          수거가 0건이어도 월정액을 청구 대상으로 올립니다.
--                   (자동으로 확정하지는 않습니다 — 목록에 올라올 뿐이고
--                    확정은 여전히 사람이 누릅니다)
--
--   시스템이 짐작해 기본값을 true 로 두지 않습니다. 계약서를 모르는 채
--   기본료를 자동으로 청구하면 병원에 잘못된 청구서가 나갑니다.
--
--  계약 기간을 함께 봅니다
--
--   flat_fee_when_empty 가 켜져 있어도, 계약 시작 전·종료 후 달에는
--   올리지 않습니다. 이미 있는 contract_start / contract_end 를 씁니다 —
--   해지한 거래처에 기본료가 계속 나가는 것이 가장 위험합니다.
-- ─────────────────────────────────────────────────────────────────────────────

alter table public.clients
  add column if not exists flat_fee_when_empty boolean not null default false;

comment on column public.clients.flat_fee_when_empty is
  '월정액을 수거 0건인 달에도 청구하는 계약인지 (0035). 계약서를 보고 사람이 켭니다.';

--  RLS 는 표 단위입니다. 거래처 표의 기존 정책이 그대로 적용되므로
--  새 정책을 만들지 않습니다.


-- ── DB 버전 ──────────────────────────────────────────────────────────────────

create or replace function public.app_schema_version()
returns integer
language sql
stable
as $$ select 35 $$;

revoke all on function public.app_schema_version() from public;
grant execute on function public.app_schema_version() to authenticated;

comment on function public.app_schema_version() is
  'DB 스키마 버전 (0035). 화면이 기대 버전과 맞춰 보고 낮으면 업데이트 안내를 띄웁니다.';
