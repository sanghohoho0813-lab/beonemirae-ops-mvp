--
--  ⚠ 이 파일은 「이렇게 넣겠습니다」를 적어 둔 것입니다. 대표님이 표를 보시고
--     승인하신 뒤에 실행하시면 됩니다.
--
--  ── 어떻게 확인했나 ──────────────────────────────────────────────────────
--
--   대표님이 외부에서 확인해 주신 후보 + 공개 의료기관 정보,
--   **두 가지가 맞을 때만** 넣습니다. 하나만 맞으면 안 넣습니다.
--
--   ⚠ 거래명세서 엑셀에는 주소가 없습니다. 다시 확인했습니다 — 엑셀의
--     `where` 칸은 「2026 거래명세서 17행」처럼 **셀 위치**이지 장소가
--     아닙니다. 그래서 엑셀은 이름 대조에만 썼습니다.
--
--   ⚠ 이름이 다르거나, 같은 이름이 여러 곳이거나, 출처가 하나뿐인 곳은
--     **넣지 않습니다.** 엉뚱한 주소를 넣으면 기사님이 엉뚱한 곳으로 갑니다.
--     안 넣는 것이 잘못 넣는 것보다 낫습니다.
--
--  ── 기존 값을 덮지 않습니다 ──────────────────────────────────────────────
--
--   `coalesce(nullif(address,''), …)` 로, **이미 주소가 있으면 그대로 둡니다.**
--   지금은 11곳 모두 비어 있는 것으로 확인됐지만(대표님 확인표), 그 사이에
--   누가 넣었을 수 있으므로 덮어쓰지 않게 만듭니다.
--   여러 번 실행해도 안전합니다.
-- ═══════════════════════════════════════════════════════════════════════════

begin;

with 확정(이름, 주소) as (values
  ('더원요양병원',       '경기도 용인시 기흥구 용구대로 2252'),
  ('남양주백병원',       '경기도 남양주시 진접읍 해밀예당1로 30-25'),
  ('서울본브릿지병원',    '서울특별시 강남구 도곡로 214 롤스웰빌딩 (도곡동)'),
  ('엠에스병원',         '서울특별시 송파구 삼학사로 53 태영빌딩 1~7층 (삼전동)'),
  ('서울온케어의원',      '경기도 남양주시 다산중앙로123번길 21-5, 8~9층 (다산동)'),
  ('해올요양병원',       '경기도 부천시 원미구 신흥로 350 SB타워Ⅱ (도당동)'),
  ('신세계서울병원',      '서울특별시 영등포구 경인로 841, 2·6·7·9~11층 (영등포동4가)'),
  ('삼성서울연합의원',    '경기도 남양주시 호평로67번길 1, 2층 (호평동)')
)
update public.clients c
   set address    = coalesce(nullif(btrim(c.address), ''), 확정.주소),
       updated_at = case when coalesce(btrim(c.address), '') = '' then now() else c.updated_at end
  from 확정
 where c.name = 확정.이름;

-- ── 확인 ──────────────────────────────────────────────────────────────────
--  이렇게 나와야 합니다: 확정 8곳에 주소가 들어가고, 나머지 3곳은 그대로 빔
select name as 거래처,
       coalesce(nullif(address, ''), '⚠ 아직 없음') as 주소,
       case
         when name in ('오남한양병원', '목동현대웰병원', '서울인화스포츠마취통증의학과의원')
           then '확인 필요 (일부러 안 넣음)'
         when coalesce(nullif(address, ''), '') = '' then '⚠ 왜 비었는지 확인'
         else '✅'
       end as 판정
  from public.clients
 where active and name not like '[Test용]%'
 order by 판정, name;

commit;

