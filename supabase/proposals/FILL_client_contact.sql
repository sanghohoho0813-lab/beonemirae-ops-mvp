-- ═══════════════════════════════════════════════════════════════════════════
--  거래처 11곳 — 주소 · 전화 · 담당자 · 수거주기 채우기 (빈칸 채움표)
--
--  ⚠ **값이 비어 있는 채로는 실행하지 마세요.** 아무 일도 안 일어납니다.
--     아래 표의 '' 안에 대표님이 아시는 값을 넣고 실행해 주세요.
--
--  ── 왜 제가 안 채웠는가 ──────────────────────────────────────────────────
--
--   대표님이 주신 거래명세서 엑셀 11개를 전부 열어 봤습니다. 그 파일들에는
--   **주소·전화·담당자 칸이 아예 없습니다.** 병원 이름·품목·수량·금액만
--   있습니다. 그래서 제가 넣을 근거가 없습니다.
--
--   인터넷에서 「같은 이름의 병원」을 찾아 넣을 수도 있지만 그렇게 하지
--   않았습니다. 이름이 비슷한 다른 병원 주소를 넣으면 기사님이 **엉뚱한
--   곳으로 갑니다.** 지어내지 않습니다.
--
--  ── 채우면 무엇이 좋아지는가 ─────────────────────────────────────────────
--
--   · 수거 입력 화면에 병원 주소가 뜹니다 (지금은 「주소 미등록」).
--   · 전화번호를 기사님이 **누르면 바로 전화**가 걸립니다.
--   · 담당자 이름이 보여, 도착해서 누구를 찾아야 하는지 압니다.
--
--  ── 안 아는 칸은 어떻게 하나 ─────────────────────────────────────────────
--
--   그 줄만 지우고 실행하시면 됩니다. 아는 것부터 넣으시면 되고,
--   나중에 이 파일을 다시 열어 나머지를 넣고 또 실행하셔도 됩니다.
--   여러 번 실행해도 안전합니다 (같은 값을 다시 덮어쓸 뿐입니다).
--
--  ⚠ **빈 문자열('')로 두면 그 칸은 건드리지 않습니다.** 이미 들어 있는
--    값이 실수로 지워지지 않게 그렇게 만들었습니다.
-- ═══════════════════════════════════════════════════════════════════════════

begin;

with 입력(이름, 주소, 전화, 담당자, 주기) as (values
  --  이름 ───────────────────────  주소 ─────  전화 ─────  담당자 ──  주기 ────
  ('남양주백병원',                    '',        '',        '',      ''),
  ('더원요양병원',                    '',        '',        '',      ''),
  ('목동현대웰병원',                  '',        '',        '',      ''),
  ('삼성서울연합의원',                '',        '',        '',      ''),
  ('서울본브릿지병원',                '',        '',        '',      ''),
  ('서울온케어의원',                  '',        '',        '',      ''),
  ('서울인화스포츠마취통증의학과의원',  '',        '',        '',      ''),
  ('신세계서울병원',                  '',        '',        '',      ''),
  ('엠에스병원',                      '',        '',        '',      ''),
  ('오남한양병원',                    '',        '',        '',      ''),
  ('해올요양병원',                    '',        '',        '',      '')
  --  주기는 이 중 하나로 적어 주세요:
  --    '주 1회' · '주 2회' · '주 3회' · '주 4회' · '주 5회' · '격주' · '월 1회'
)
update public.clients c
   set address           = case when nullif(btrim(입력.주소),   '') is not null then btrim(입력.주소)   else c.address end,
       phone             = case when nullif(btrim(입력.전화),   '') is not null then btrim(입력.전화)   else c.phone end,
       manager           = case when nullif(btrim(입력.담당자), '') is not null then btrim(입력.담당자) else c.manager end,
       collection_cycle  = case when nullif(btrim(입력.주기),   '') is not null then btrim(입력.주기)   else c.collection_cycle end,
       updated_at        = now()
  from 입력
 where c.name = 입력.이름;

-- ── 확인 ──────────────────────────────────────────────────────────────────
select name as 거래처,
       coalesce(nullif(address, ''), '⚠ 아직 없음') as 주소,
       coalesce(nullif(phone,   ''), '⚠ 아직 없음') as 전화,
       coalesce(nullif(manager, ''), '⚠ 아직 없음') as 담당자,
       collection_cycle as 주기
  from public.clients
 where active
 order by name;

commit;
