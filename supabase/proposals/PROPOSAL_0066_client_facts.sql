-- ═══════════════════════════════════════════════════════════════════════════
--  0066 (제안) — 거래처 11곳의 사실관계 바로잡기
--
--  ⚠ 아직 **실행하지 않았습니다.** 운영 자료를 고치는 SQL 이라 대표님이
--     읽어 보시고 직접 실행하시도록 남깁니다.
--
--  ── 왜 필요한가 ──────────────────────────────────────────────────────────
--
--   대표님이 11곳을 다 넣어 주셨습니다. **이름은 11곳 모두 정확히 들어와
--   있습니다.** 다만 속성 칸이 전부 같은 값으로 채워져 있어서, 거래명세서
--   엑셀과 대조하니 세 가지가 사실과 다릅니다.
--
--   ① 기저귀 수거 여부가 3곳 틀립니다  ← **가장 급한 것**
--
--      DB 는 11곳 전부 「기저귀 안 함」입니다. 그런데 엑셀에는:
--
--        더원요양병원    7월 기저귀 10,510kg · 8월 2,270kg  (매출의 대부분)
--        목동현대웰병원  기저귀만 수거 — **의료폐기물은 한 건도 없음**
--        해올요양병원    기저귀 수거 있음
--
--      이 칸이 꺼져 있으면 **그 병원에 기저귀 일정을 잡을 수 없고**,
--      기저귀 차량(4·5호차)도 배차되지 않습니다. 목동현대웰병원은
--      정반대로 들어가 있어, 실제로 하는 일은 못 하고 안 하는 일만
--      할 수 있는 상태입니다.
--
--   ② 수거 주기가 11곳 전부 「주 1회」입니다
--
--      엑셀의 8월 수거일을 세어 보면:
--        해올요양병원      5일 (8/3,5,6,10,11)
--        신세계서울병원    3일 (8/4,7,11)
--        목동현대웰병원    3일 (8/3,6,10)
--        서울본브릿지병원  2일 (8/6,10)
--        더원요양병원      2일 (8/2,5)
--
--      ⚠ 다만 8월은 아직 중순까지밖에 없어서, 이 숫자만으로 「주 3회」라고
--        단정하지 않겠습니다. **아래에서 주기는 건드리지 않습니다.**
--        대표님이 실제 계약 주기를 알려 주시면 그때 넣겠습니다.
--        지어내지 않습니다.
--
--   ③ 업종이 11곳 전부 「병원」입니다
--
--      이름에 그대로 적혀 있습니다 — 요양병원 2곳, 의원 3곳.
--      업종은 화면 분류·통계에만 쓰이고 돈 계산에는 안 쓰입니다.
--
--  ── 기존 데이터에 미치는 영향 ────────────────────────────────────────────
--
--   · 수거·자재·청구·입금 기록은 **한 줄도 건드리지 않습니다.**
--   · clients 표의 세 칸(collects_diaper, collects_medical_waste, type)만
--     바꿉니다. 금액 칸(pricing)은 손대지 않습니다.
--   · 이름으로 찾습니다. 못 찾으면 그 줄은 그냥 넘어갑니다(0건 갱신).
--     실행 뒤 확인표에서 몇 줄이 바뀌었는지 보실 수 있습니다.
--
--  ── 실행하면 얻는 것 ─────────────────────────────────────────────────────
--
--   · 더원·해올·목동현대웰에 **기저귀 일정을 잡을 수 있게** 됩니다.
--   · 목동현대웰병원에 의료폐기물 차량이 잘못 배차되지 않습니다.
--
--  ── 되돌리기 ─────────────────────────────────────────────────────────────
--   맨 아래 주석에 원래 값으로 되돌리는 SQL 을 적어 두었습니다.
-- ═══════════════════════════════════════════════════════════════════════════

begin;

-- ① 기저귀 수거 — 엑셀에 기저귀 수거/매출이 있는 3곳
update public.clients set collects_diaper = true, updated_at = now()
 where name in ('더원요양병원', '해올요양병원', '목동현대웰병원');

-- ①-b 목동현대웰병원은 엑셀 전 기간에 **의료폐기물이 한 건도 없습니다**.
--     기저귀 전용 거래처입니다.
--     ⚠ 혹시 의료폐기물도 하시는데 엑셀에만 안 잡힌 것이라면 이 줄은 빼고
--       실행해 주세요. 지금 켜져 있는 것을 끄는 유일한 줄입니다.
update public.clients set collects_medical_waste = false, updated_at = now()
 where name = '목동현대웰병원';

-- ③ 업종 — 이름에 적힌 그대로
update public.clients set type = '요양병원', updated_at = now()
 where name in ('더원요양병원', '해올요양병원');
update public.clients set type = '의원', updated_at = now()
 where name in ('서울온케어의원', '삼성서울연합의원', '서울인화스포츠마취통증의학과의원');

-- ── 확인 ──────────────────────────────────────────────────────────────────
select name, type, collects_medical_waste as 의료, collects_diaper as 기저귀,
       collection_cycle as 주기,
       case when address is null or address = '' then '⚠ 주소 없음' else address end as 주소,
       case when phone   is null or phone   = '' then '⚠ 전화 없음' else phone   end as 전화
  from public.clients
 where active
 order by name;

commit;

